// Regenerates the "Awesome avatar art" list in README.md between the AWESOME markers.
// DiceBear entries come from each style definition's own metadata (creator, source, licence).
import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";

const root = new URL("..", import.meta.url).pathname;
const require = createRequire(root + "package.json");
const dist = require.resolve("@dicebear/styles/micah.json").replace(/micah\.min\.json$|micah\.json$/, "");
const BUILT_IN = { micah: "micah", avataaars: "avataaars", gaze: "gaze" };
const rows = [];
for (const f of readdirSync(dist).filter((f) => f.endsWith(".min.json")).sort()) {
  const id = f.replace(".min.json", "");
  if (id.endsWith("-neutral")) continue;                       // the neutral variants are face-only versions of the same art
  const m = JSON.parse(readFileSync(dist + f, "utf8")).meta || {};
  const name = id.split("-").map((w) => w[0].toUpperCase() + w.slice(1)).join(" ");
  const src = m.source?.url ? `[${name}](${m.source.url})` : name;
  const by = m.creator?.url ? `[${m.creator.name}](${m.creator.url})` : m.creator?.name || "DiceBear";
  const lic = m.license?.url ? `[${m.license.name}](${m.license.url})` : m.license?.name || "";
  const status = BUILT_IN[id] ? `built in: \`awesome-agent-avatars/styles/${BUILT_IN[id]}\`` : `\`dicebearStyle()\` + \`@dicebear/styles/${id}.json\``;
  rows.push(`| ${src} | ${by} | ${lic} | ${status} |`);
}
const OTHER = [
  "| [react-nice-avatar](https://github.com/dapi-labs/react-nice-avatar) | Dapi | MIT | built in: `awesome-agent-avatars/styles/nice` |",
  "| [Fluent Emoji](https://github.com/microsoft/fluentui-emoji) (3D) | Microsoft | MIT | built in: `awesome-agent-avatars/styles/fluent` (with 3D raised arms) |",
  "| [Boring Avatars](https://github.com/boringdesigners/boring-avatars) | Boring Designers | MIT | `pictureStyle()` or a parts style (help wanted) |",
  "| [OpenMoji](https://github.com/hfg-gmuend/openmoji) | HfG Schwäbisch Gmünd | CC BY-SA 4.0 | `pictureStyle()` (share-alike applies to the art) |",
  "| [Noto Emoji](https://github.com/googlefonts/noto-emoji) | Google | Apache 2.0 (images), OFL 1.1 (fonts) | `pictureStyle()` |",
  "| Your product's mascot | you | yours | `pictureStyle({ src, faces })` |",
];
const block = `<!-- AWESOME:START (generated by scripts/gen-awesome.mjs) -->
Open-source avatar art you can animate with this engine today. Check each licence before you ship; some require attribution or share-alike.

<details>
<summary><b>${rows.length + OTHER.length - 1} avatar systems</b>: ${rows.length} DiceBear styles plus ${OTHER.length - 1} other sets (click to expand)</summary>

| Art | Creator | Licence | How to use it |
|---|---|---|---|
${[...OTHER, ...rows].join("\n")}

</details>

Know another open avatar set, or made a style? Open a PR adding it here.
<!-- AWESOME:END -->`;
const readme = readFileSync(root + "README.md", "utf8");
const out = readme.replace(/<!-- AWESOME:START[\s\S]*?<!-- AWESOME:END -->/, block);
if (out === readme && !readme.includes("AWESOME:START")) throw new Error("README has no AWESOME markers");
writeFileSync(root + "README.md", out);
console.log("listed", rows.length, "DiceBear styles +", OTHER.length, "others");
